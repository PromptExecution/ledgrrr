#!/usr/bin/env node
// Vendors crates/ui/bindings.ts (tauri-specta generated) into this Vite
// project's own src/ tree as src/generated/bindings.ts.
//
// Why a copy instead of importing the canonical file directly: bindings.ts
// imports the bare specifier "@tauri-apps/api/core", and Node/Vite/Rollup
// module resolution for a bare specifier only walks up from the *importing
// file's own directory* looking for node_modules. crates/ui/ has no
// ancestor node_modules of its own (this npm project's node_modules lives
// at ui/docs/node_modules), so importing crates/ui/bindings.ts directly
// fails to resolve "@tauri-apps/api/core" at both typecheck and bundle
// time. Vendoring an exact copy inside this project's own src/ tree makes
// it a normal same-project import that resolves node_modules the usual way.
//
// The canonical source of truth stays crates/ui/bindings.ts, regenerated by
// `cargo build -p ledgerr-host --bin host-tauri` (see Justfile's
// check-drift target). This script never edits that file — only copies it.
// Run automatically before `dev`/`build` (see package.json).

import { copyFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', '..', 'crates', 'ui', 'bindings.ts');
const destDir = join(here, '..', 'src', 'generated');
const dest = join(destDir, 'bindings.ts');

const contents = readFileSync(src, 'utf8');
if (!contents.includes('generated by Tauri Specta')) {
  throw new Error(`refusing to sync — ${src} does not look like a tauri-specta generated file`);
}

mkdirSync(destDir, { recursive: true });
copyFileSync(src, dest);
console.log(`[sync-bindings] copied ${src} -> ${dest}`);
